// Builds playground/graceholder.js: the library plus every vocabulary pack (registered), as one browser
// script that defines the global `Graceholder`. The playground loads it with a plain <script> tag, so the
// page works from file:// (ES modules do not) and from GitHub Pages. The bundle is committed;
// test/playground-bundle.test.js fails when it is stale. Run `npm run playground:build` after changing src/.
import { build } from "esbuild";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const OUT = `${root}playground/graceholder.js`;

export async function bundle() {
  const result = await build({
    stdin: {
      contents: `export * from ${JSON.stringify(`${root}src/index.js`)};\nimport { registerPack } from ${JSON.stringify(`${root}src/index.js`)};\nimport { allPacks } from ${JSON.stringify(`${root}src/packs/index.js`)};\nfor (const p of allPacks) registerPack(p);`,
      resolveDir: root,
      loader: "js",
    },
    bundle: true,
    format: "iife",
    globalName: "Graceholder",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  return `/* @johnhenry/graceholder browser bundle for the playground. Generated by scripts/build-playground.mjs; do not edit. */\n${result.outputFiles[0].text}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundle();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
      console.error("playground/graceholder.js is stale; run npm run playground:build");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${text.length} bytes)`);
  }
}
