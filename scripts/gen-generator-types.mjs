// Writes src/generator-types.d.ts: the JSON type of each catalogue generator, derived from the
// runtime's own genSdlType (the single source of truth for generator output types).
// `node scripts/gen-generator-types.mjs` writes it; `--check` fails when it is stale (see test/typed-sync.test.js).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { GENERATOR_NAMES } from "../src/generators.js";
import { genSdlType } from "../src/infer.js";
import { allPacks } from "../src/packs/index.js";

const JS = { Int: "number", Float: "number", Boolean: "boolean", ID: "string", DateTime: "string", String: "string" };

export function render() {
  const entries = new Map();
  for (const name of GENERATOR_NAMES) {
    let t = JS[genSdlType(name, {})];
    if (name === "id.int") t = "string | number"; // a number, or a string with { string: true }
    if (name === "time.deleted") t = "string | null"; // null by default
    if (name === "oneOf") t = "unknown"; // depends on its values
    entries.set(name, t);
  }
  for (const pack of allPacks) {
    const base = Object.fromEntries(GENERATOR_NAMES.map((n) => [n, () => null]));
    for (const name of Object.keys(pack.generators({ ...pack.vocab }, base))) {
      if (entries.has(name) && !pack.types?.[name]) continue;
      entries.set(name, JS[pack.types?.[name] ?? "String"]);
    }
  }
  const lines = [...entries].sort(([a], [b]) => (a < b ? -1 : 1)).map(([n, t]) => `  ${JSON.stringify(n)}: ${t};`);
  return `// GENERATED by scripts/gen-generator-types.mjs from the runtime catalogue. Do not edit.\n/** The JSON type each named generator produces (used by the type-level query parser for @gen). */\nexport interface GeneratorTypes {\n${lines.join("\n")}\n}\n`;
}

const target = fileURLToPath(new URL("../src/generator-types.d.ts", import.meta.url));
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== render()) {
      console.error("src/generator-types.d.ts is stale; run node scripts/gen-generator-types.mjs");
      process.exit(1);
    }
  } else writeFileSync(target, render());
}
